def read_ambpreset(path):
    """Pull the parameter map out of a .ambpreset.

    The file is juce::copyXmlToBinary output: a small binary header ('VC2!'
    magic plus a size field) followed by the literal XML. Rather than decode
    the header we just seek to the '<?xml' marker, which is stable across
    every file here.

    Three quirks, present in all 21:
      * 'crossfeed' and 'oversampling' are parameters that no longer exist in
        the layout - dropped.
      * hicut is written as <PARAM id="hicut"/> with NO value attribute, so it
        falls back to its default. Preserved as a default rather than guessed.
      * a 'currentPresetName' property may be present - not a parameter.
    """
    raw = open(path, "rb").read()
    start = raw.find(b"<?xml")
    if start < 0:
        raise ValueError("%s: no XML payload" % path)
    text = raw[start:].decode("utf-8", "replace")

    values = {}
    for m in re.finditer(r'<PARAM\s+id="([^"]+)"(?:\s+value="([^"]*)")?\s*/>', text):
        pid, val = m.group(1), m.group(2)
        if pid not in P.BY_SYM:
            continue                      # crossfeed, oversampling
        if val is None or val == "":
            continue                      # hicut - leave at default
        values[pid] = float(val)
    return values


def full_port_map(values):
    """Fill every port. A preset that omits a port leaves whatever the
    previous preset set, so partial presets make the plugin's sound depend on
    load order. All 36 always."""
    out = {}
    for p in P.CONTROL_PORTS:
        v = values.get(p["sym"], p["default"])
        v = max(float(p["lo"]), min(float(p["hi"]), float(v)))
        out[p["sym"]] = int(round(v)) if p["kind"] in ("enum", "bool") else v
    return out


def parse_preset_defaults():
    """PRESET_DEFAULTS[7] out of Source/AlgorithmPresets.h.

    Parsed rather than retyped so the seven '<ALGO> Default' presets cannot
    drift from the values the DSP would have loaded.
    """
    src = open(os.path.join(REPO, "Source", "AlgorithmPresets.h"),
               encoding="utf-8").read()

    m = re.search(r"PRESET_DEFAULTS\s*=\s*\{\s*\{(.*?)\}\s*\}\s*;", src, re.S)
    if not m:
        raise ValueError("PRESET_DEFAULTS not found in AlgorithmPresets.h")

    body = re.sub(r"//[^\n]*", "", m.group(1))
    rows = re.findall(r"\{([^{}]*)\}", body)
    if len(rows) != 7:
        raise ValueError("expected 7 PRESET_DEFAULTS rows, got %d" % len(rows))

    keys = ["roomSize", "decayTime", "hfDamp", "lfAbsorb", "diffusion",
            "modAmount", "modRate", "erLevel", "saturation"]
    out = []
    for row in rows:
        nums = [float(x) for x in re.findall(r"-?\d+\.?\d*(?=f)", row)]
        if len(nums) != 9:
            raise ValueError("expected 9 fields, got %d in %r" % (len(nums), row))
        out.append(dict(zip(keys, nums)))
    return out


def algorithm_default_presets():
    """The seven per-algorithm starting points.

    Mirrors FDNReverbAudioProcessor::loadPresetDefaults(). Note it deliberately
    IGNORES def.hfDamp / def.lfAbsorb and forces both to 0, along with all ten
    rtband trims and the three tilts - the comment there is explicit that
    selecting an algorithm should reproduce that algorithm's own RT60 curve
    with no correction layered on top.
    """
    defaults = parse_preset_defaults()
    presets = []

    for i, d in enumerate(defaults):
        v = {p["sym"]: p["default"] for p in P.CONTROL_PORTS}
        v["algorithm"] = i
        v["roomsize"] = d["roomSize"]
        v["decaytime"] = d["decayTime"]
        v["diffusion"] = d["diffusion"]
        v["modamount"] = d["modAmount"]
        v["modrate"] = d["modRate"]
        v["erlevel"] = d["erLevel"]
        v["saturation"] = d["saturation"]
        v["hfdamping"] = 0.0
        v["lfabsorption"] = 0.0
        for b in range(10):
            v["rtband%d" % b] = 1.0
        v["tiltlow"] = v["tiltmid"] = v["tilthigh"] = 1.0

        presets.append(("%s Default" % P.ALGORITHMS[i], v))

    return presets


def slug(label):
    return re.sub(r"[^A-Za-z0-9]+", "-", label).strip("-")


def collect_presets():
    """21 factory + 7 algorithm defaults, grouped by algorithm."""
    factory = []
    pdir = os.path.join(REPO, "Presets")
    for fn in sorted(os.listdir(pdir)):
        if not fn.endswith(".ambpreset"):
            continue
        label = fn[: -len(".ambpreset")]
        factory.append((label, full_port_map(read_ambpreset(os.path.join(pdir, fn)))))

    if len(factory) != 21:
        print("  warning: expected 21 factory presets, found %d" % len(factory))

    algo = [(label, full_port_map(v)) for label, v in algorithm_default_presets()]

    both = factory + algo
    both.sort(key=lambda kv: (kv[1]["algorithm"],
                              not kv[0].endswith("Default"),
                              kv[0]))
    return both


def preset_stanza(uri, label, values):
    ports = ",\n".join(
        '\t\t[ lv2:symbol "%s" ; pset:value %s ]' % (p["sym"], num(values[p["sym"]]))
        for p in P.CONTROL_PORTS)
    return """%s
\ta pset:Preset ;
\tlv2:appliesTo <%s> ;
\trdfs:label %s ;
\tlv2:port
%s .
""" % (uri, URI, ttl_string(label), ports)


def gen_presets(presets):
    header = """%s@prefix lv2:  <http://lv2plug.in/ns/lv2core#> .
@prefix pset: <http://lv2plug.in/ns/ext/presets#> .
@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .

""" % PROLOGUE

    body = [header]
    for label, values in presets:
        body.append(preset_stanza("<%s%s>" % (PRESET_NS, slug(label)), label, values))
    write(os.path.join(BUNDLE, "presets.ttl"), "\n".join(body))

    # The subject must be the SAME relative URI the manifest declares, i.e.
    # <default-preset>, not <>. Both resolve against their own file's base, so
    # <> here would name default-preset.ttl while the manifest names
    # <bundle>/default-preset - two different subjects, and lilv would find a
    # preset with no port values. MOD's own bundles use <default-preset> in
    # both files for exactly this reason (mod-mda-Leslie.lv2).
    defaults = full_port_map({})
    write(os.path.join(BUNDLE, "default-preset.ttl"),
          header + preset_stanza("<default-preset>", "Default", defaults))


# ---------------------------------------------------------------------------
# manifest.ttl
# ---------------------------------------------------------------------------
def gen_manifest(presets):
    """MOD's convention: declare every preset inline in the manifest and point
    at the data file with rdfs:seeAlso, so mod-ui can list them without
    parsing presets.ttl. See mod-mda-Leslie.lv2/manifest.ttl."""
    out = ["""%s@prefix lv2:  <http://lv2plug.in/ns/lv2core#> .
@prefix pset: <http://lv2plug.in/ns/ext/presets#> .
@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .

<%s>
    a lv2:Plugin ;
    lv2:binary <AmbienceReverb.so> ;
    rdfs:seeAlso <AmbienceReverb.ttl> , <modgui.ttl> .

<default-preset>
    a pset:Preset ;
    lv2:appliesTo <%s> ;
    rdfs:label "Default" ;
    rdfs:seeAlso <default-preset.ttl> .
""" % (PROLOGUE, URI, URI)]

    for label, _ in presets:
        out.append("""<%s%s>
    a pset:Preset ;
    lv2:appliesTo <%s> ;
    rdfs:label %s ;
    rdfs:seeAlso <presets.ttl> .
""" % (PRESET_NS, slug(label), URI, ttl_string(label)))

    write(os.path.join(BUNDLE, "manifest.ttl"), "\n".join(out))


# ---------------------------------------------------------------------------
def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("  %s" % os.path.relpath(path, REPO))


def main():
    print("Generating:")
    gen_ports_h()
    gen_plugin_ttl()
    gen_modgui_ttl()
    gen_javascript()
    presets = collect_presets()
    gen_presets(presets)
    gen_manifest(presets)
    print("\n%d control ports, %d presets (+ Default)"
          % (len(P.CONTROL_PORTS), len(presets)))


if __name__ == "__main__":
    main()
