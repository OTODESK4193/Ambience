#!/usr/bin/env python3
"""
Generate everything in the Ambience LV2 bundle that is derived from something
else, so none of it can drift:

    lv2/src/ports.h        port indices + defaults for the C++ wrapper
    AmbienceReverb.ttl     the port descriptions mod-ui and lilv read
    manifest.ttl           plugin + one inline stanza per preset
    presets.ttl            28 presets
    default-preset.ttl     the layout defaults, as MOD's own bundles ship
    modgui.ttl             modgui:port entries for all 40 ports

Sources of truth:
    lv2/tools/ports.py         the port table (transcribed from
                               Source/PluginParameters.cpp)
    Presets/*.ambpreset        21 factory presets
    Source/AlgorithmPresets.h  PRESET_DEFAULTS -> 7 "<ALGO> Default" presets

Run from the repo root:  python3 lv2/tools/gen_bundle.py
"""

import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ports as P

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

URI = "https://github.com/OTODESK4193/Ambience1.0.1"
PRESET_NS = URI + "/presets#"
VERSION = (1, 1)  # minorVersion, microVersion

BUNDLE = os.path.join(REPO, "lv2", "bundle")
PORTS_H = os.path.join(REPO, "lv2", "src", "ports.h")

PROLOGUE = "# Generated by lv2/tools/gen_bundle.py - do not edit by hand.\n"


# ---------------------------------------------------------------------------
# helpers
# ---------------------------------------------------------------------------
def num(v):
    """TTL numeric literal. Integers must not be written as 1.0 where lilv
    expects an integer-typed port value, and floats must keep a decimal point
    or they parse as xsd:integer."""
    if isinstance(v, int):
        return str(v)
    if float(v).is_integer() and abs(v) < 1e15:
        return "%.1f" % v
    return repr(round(float(v), 6))


def ttl_string(s):
    return '"%s"' % s.replace("\\", "\\\\").replace('"', '\\"')


UNIT_TTL = {"ms": "units:ms", "s": "units:s", "hz": "units:hz", "db": "units:db"}


# ---------------------------------------------------------------------------
# lv2/src/ports.h
# ---------------------------------------------------------------------------
def gen_ports_h():
    out = ["""#pragma once
// Generated by lv2/tools/gen_bundle.py from lv2/tools/ports.py - do not edit.
//
// The same table generates AmbienceReverb.ttl, so a port cannot exist in the
// TTL without existing here (and vice versa) and the indices cannot disagree.

#define AMBIENCE_URI "%s"

namespace ambience {

enum PortIndex {""" % URI]

    for i, (sym, _name, _dir) in enumerate(P.AUDIO_PORTS):
        out.append("    PORT_%-14s = %d," % (sym.upper(), i))
    out.append("")

    for i, p in enumerate(P.CONTROL_PORTS):
        out.append("    PORT_%-14s = %d," % (p["sym"].upper(),
                                             P.FIRST_CONTROL_INDEX + i))
    out.append("")
    out.append("    PORT_COUNT              = %d" %
               (len(P.AUDIO_PORTS) + len(P.CONTROL_PORTS)))
    out.append("};")
    out.append("")
    out.append("// Indices into the control[] array, i.e. port index minus"
               " kFirstControlPort.")
    out.append("enum ControlIndex {")
    for i, p in enumerate(P.CONTROL_PORTS):
        out.append("    CTL_%-15s = %d," % (p["sym"].upper(), i))
    out.append("};")
    out.append("")
    out.append("constexpr int kFirstControlPort = %d;" % P.FIRST_CONTROL_INDEX)
    out.append("constexpr int kNumControlPorts  = %d;" % len(P.CONTROL_PORTS))
    out.append("")
    out.append("struct ControlDesc { const char* sym; float lo, hi, def; };")
    out.append("")
    out.append("constexpr ControlDesc kControls[kNumControlPorts] = {")
    for p in P.CONTROL_PORTS:
        out.append('    { "%s", %sf, %sf, %sf },'
                   % (p["sym"], num(float(p["lo"])), num(float(p["hi"])),
                      num(float(p["default"]))))
    out.append("};")
    out.append("")
    out.append("} // namespace ambience")
    out.append("")

    write(PORTS_H, "\n".join(out))


# ---------------------------------------------------------------------------
# AmbienceReverb.ttl
# ---------------------------------------------------------------------------
def gen_plugin_ttl():
    out = [PROLOGUE, """@prefix doap:   <http://usefulinc.com/ns/doap#> .
@prefix foaf:   <http://xmlns.com/foaf/0.1/> .
@prefix lv2:    <http://lv2plug.in/ns/lv2core#> .
@prefix pprops: <http://lv2plug.in/ns/ext/port-props#> .
@prefix rdf:    <http://www.w3.org/1999/02/22-rdf-syntax-ns#> .
@prefix rdfs:   <http://www.w3.org/2000/01/rdf-schema#> .
@prefix units:  <http://lv2plug.in/ns/extensions/units#> .

<%s>
    a lv2:Plugin , lv2:ReverbPlugin ;
    doap:name "Ambience Reverb" ;
    doap:license <https://www.gnu.org/licenses/agpl-3.0.html> ;
    doap:maintainer [
        foaf:name "OTODESK" ;
        foaf:homepage <https://github.com/OTODESK4193/Ambience1.0.1>
    ] ;
    lv2:minorVersion %d ;
    lv2:microVersion %d ;
    lv2:optionalFeature lv2:hardRTCapable ;
    rdfs:comment \"\"\"16-channel Feedback Delay Network algorithmic reverb.

FWHT feedback matrix with coprime prime-number delay allocation, seven
algorithms (Room, Hall, Plate, Spring, Goldfoil), per-channel 10-band
Valimaki-Liski cascade GEQ absorption for frequency-dependent RT60,
ISM early reflections, ADAA saturation, ducking and a brick-wall limiter.\"\"\" ;
""" % (URI, VERSION[0], VERSION[1])]

    port_blocks = []

    for i, (sym, name, direction) in enumerate(P.AUDIO_PORTS):
        cls = "lv2:InputPort" if direction == "input" else "lv2:OutputPort"
        port_blocks.append("""    [
        a %s , lv2:AudioPort ;
        lv2:index %d ;
        lv2:symbol "%s" ;
        lv2:name "%s"
    ]""" % (cls, i, sym, name))

    for i, p in enumerate(P.CONTROL_PORTS):
        idx = P.FIRST_CONTROL_INDEX + i
        lines = ["        a lv2:InputPort , lv2:ControlPort ;",
                 "        lv2:index %d ;" % idx,
                 '        lv2:symbol "%s" ;' % p["sym"],
                 '        lv2:name "%s" ;' % p["name"]]

        props = []
        if p["kind"] == "enum":
            props += ["lv2:integer", "lv2:enumeration"]
        elif p["kind"] == "bool":
            props += ["lv2:toggled"]
        elif p["skew"] < 1.0:
            # LV2's only nonlinear taper. Not identical to a JUCE skew but the
            # same intent: put the useful range under the first half of the
            # knob. predelay keeps skew 1.0 precisely because its 0.0 minimum
            # makes a logarithmic taper undefined.
            props += ["pprops:logarithmic"]

        for prop in props:
            lines.append("        lv2:portProperty %s ;" % prop)

        is_int = p["kind"] in ("enum", "bool")
        conv = int if is_int else float
        lines.append("        lv2:default %s ;" % num(conv(p["default"])))
        lines.append("        lv2:minimum %s ;" % num(conv(p["lo"])))
        lines.append("        lv2:maximum %s" % num(conv(p["hi"])))

        if p["points"]:
            lines[-1] += " ;"
            # One predicate, a comma-separated object list. Repeating
            # `lv2:scalePoint` after each comma is not Turtle.
            pts = ['[ rdfs:label "%s" ; rdf:value %d ]' % (label, v)
                   for v, label in enumerate(p["points"])]
            lines.append("        lv2:scalePoint "
                         + (" ,\n" + " " * 23).join(pts))

        if p["unit"]:
            lines[-1] += " ;"
            lines.append("        units:unit %s" % UNIT_TTL[p["unit"]])

        port_blocks.append("    [\n" + "\n".join(lines) + "\n    ]")

    out.append("    lv2:port\n" + " ,\n".join(port_blocks) + " .\n")
    write(os.path.join(BUNDLE, "AmbienceReverb.ttl"), "\n".join(out))


