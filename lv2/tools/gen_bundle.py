def gen_ports_h():
    out = ["""#pragma once
// Generated by lv2/tools/gen_bundle.py from lv2/tools/ports.py - do not edit.
//
// The same table generates AmbienceReverb.ttl, so a port cannot exist in the
// TTL without existing here (and vice versa) and the indices cannot disagree.

#define AMBIENCE_URI "%s"

namespace ambience {

enum PortIndex {""" % URI]

    for i, (sym, _name, _dir) in enumerate(P.AUDIO_PORTS):
        out.append("    PORT_%-14s = %d," % (sym.upper(), i))
    out.append("")

    for i, p in enumerate(P.CONTROL_PORTS):
        out.append("    PORT_%-14s = %d," % (p["sym"].upper(),
                                             P.FIRST_CONTROL_INDEX + i))
    out.append("")

    for i, p in enumerate(P.OUTPUT_PORTS):
        out.append("    PORT_%-14s = %d," % (p["sym"].upper(),
                                             P.FIRST_OUTPUT_INDEX + i))
    out.append("")
    out.append("    PORT_COUNT              = %d" %
               (len(P.AUDIO_PORTS) + len(P.CONTROL_PORTS) + len(P.OUTPUT_PORTS)))
    out.append("};")
    out.append("")
    out.append("// Indices into the control[] array, i.e. port index minus"
               " kFirstControlPort.")
    out.append("enum ControlIndex {")
    for i, p in enumerate(P.CONTROL_PORTS):
        out.append("    CTL_%-15s = %d," % (p["sym"].upper(), i))
    out.append("};")
    out.append("")
    out.append("constexpr int kFirstControlPort = %d;" % P.FIRST_CONTROL_INDEX)
    out.append("constexpr int kNumControlPorts  = %d;" % len(P.CONTROL_PORTS))
    out.append("")
    out.append("// The first kNumSoundPorts controls are the parameters a preset")
    out.append("// is made of. The rest are preset-slot machinery and are")
    out.append("// deliberately not part of any preset.")
    out.append("constexpr int kNumSoundPorts    = %d;" % P.NUM_SOUND_PORTS)
    out.append("constexpr int kNumSlots         = %d;" % P.NUM_SLOTS)
    out.append("")
    out.append("// The slot-preset block is contiguous, and must stay that way:")
    out.append("// connect_port() resolves it by range and the DSP walks it to")
    out.append("// find the next assigned slot. There is only one button, so the")
    out.append("// HMI addressed() callback matches its port index by equality.")
    out.append("constexpr int kFirstSlotPresetPort = PORT_%s;"
               % P.SLOT_PRESET_PORTS[0]["sym"].upper())
    out.append("constexpr int kFirstSlotPresetCtl  = CTL_%s;"
               % P.SLOT_PRESET_PORTS[0]["sym"].upper())
    out.append("")
    out.append("struct ControlDesc { const char* sym; float lo, hi, def; };")
    out.append("")
    out.append("constexpr ControlDesc kControls[kNumControlPorts] = {")
    for p in P.CONTROL_PORTS:
        out.append('    { "%s", %sf, %sf, %sf },'
                   % (p["sym"], num(float(p["lo"])), num(float(p["hi"])),
                      num(float(p["default"]))))
    out.append("};")
    out.append("")
    out.append("} // namespace ambience")
    out.append("")

    write(PORTS_H, "\n".join(out))


