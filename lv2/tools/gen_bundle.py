# modgui/javascript.js
# ---------------------------------------------------------------------------
def gen_javascript():
    """Substitute the algorithm re-seed table into javascript.js.in.

    Same seven values loadPresetDefaults() writes, plus the neutral resets it
    forces, so the modgui's behaviour on an algorithm change cannot drift from
    what the VST3 does. See javascript.js.in for why this is GUI-side at all.
    """
    src = os.path.join(BUNDLE, "modgui", "javascript.js.in")
    template = open(src, encoding="utf-8").read()

    rows = []
    for i, (_label, values) in enumerate(algorithm_default_presets()):
        # Only the ports loadPresetDefaults() actually touches.
        touched = ["roomsize", "decaytime", "hfdamping", "lfabsorption",
                   "diffusion", "modamount", "modrate", "erlevel", "saturation",
                   "tiltlow", "tiltmid", "tilthigh"] \
                  + ["rtband%d" % b for b in range(10)]
        pairs = ", ".join("%s: %s" % (s, num(values[s])) for s in touched)
        rows.append("        /* %-8s */ { %s }" % (P.ALGORITHMS[i], pairs))

    table = ("    /* From PRESET_DEFAULTS in Source/AlgorithmPresets.h, via\n"
             "       loadPresetDefaults(). hfDamp/lfAbsorb from that table are\n"
             "       deliberately ignored and forced to 0, exactly as the VST3\n"
             "       does: picking an algorithm should reproduce that\n"
             "       algorithm's own RT60 curve with no correction on top. */\n"
             "    var ALGORITHM_DEFAULTS = [\n"
             + ",\n".join(rows) + "\n    ];")

    marker = "    /* [ALGORITHM_DEFAULTS] */"
    if marker not in template:
        raise ValueError("javascript.js.in lost its [ALGORITHM_DEFAULTS] marker")

    write(os.path.join(BUNDLE, "modgui", "javascript.js"),
          template.replace(marker, table))


