def num(v):
    """TTL numeric literal. Integers must not be written as 1.0 where lilv
    expects an integer-typed port value, and floats must keep a decimal point
    or they parse as xsd:integer."""
    if isinstance(v, int):
        return str(v)
    if float(v).is_integer() and abs(v) < 1e15:
        return "%.1f" % v
    return repr(round(float(v), 6))


def ttl_string(s):
    return '"%s"' % s.replace("\\", "\\\\").replace('"', '\\"')


UNIT_TTL = {"ms": "units:ms", "s": "units:s", "hz": "units:hz", "db": "units:db"}


