#!/usr/bin/env python3
"""
Generate everything in the Ambience LV2 bundle that is derived from something
else, so none of it can drift:

    lv2/src/ports.h        port indices + defaults for the C++ wrapper
    AmbienceReverb.ttl     the port descriptions mod-ui and lilv read
    manifest.ttl           plugin + one inline stanza per preset
    presets.ttl            28 presets
    default-preset.ttl     the layout defaults, as MOD's own bundles ship
    modgui.ttl             modgui:port entries for all 40 ports

Sources of truth:
    lv2/tools/ports.py         the port table (transcribed from
                               Source/PluginParameters.cpp)
    Presets/*.ambpreset        21 factory presets
    Source/AlgorithmPresets.h  PRESET_DEFAULTS -> 7 "<ALGO> Default" presets

Run from the repo root:  python3 lv2/tools/gen_bundle.py
"""

