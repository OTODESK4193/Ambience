def gen_plugin_ttl():
    out = [PROLOGUE, """@prefix doap:   <http://usefulinc.com/ns/doap#> .
@prefix foaf:   <http://xmlns.com/foaf/0.1/> .
@prefix hmi:    <http://moddevices.com/ns/hmi#> .
@prefix lv2:    <http://lv2plug.in/ns/lv2core#> .
@prefix pprops: <http://lv2plug.in/ns/ext/port-props#> .
@prefix rdf:    <http://www.w3.org/1999/02/22-rdf-syntax-ns#> .
@prefix rdfs:   <http://www.w3.org/2000/01/rdf-schema#> .
@prefix state:  <http://lv2plug.in/ns/ext/state#> .
@prefix units:  <http://lv2plug.in/ns/extensions/units#> .

<%s>
    a lv2:Plugin , lv2:ReverbPlugin ;
    doap:name "Ambience Reverb" ;
    doap:license <https://www.gnu.org/licenses/agpl-3.0.html> ;
    doap:maintainer [
        foaf:name "OTODESK" ;
        foaf:homepage <https://github.com/OTODESK4193/Ambience1.0.1>
    ] ;
    lv2:minorVersion %d ;
    lv2:microVersion %d ;
    lv2:optionalFeature lv2:hardRTCapable ;

    # Optional on purpose: without it the plugin still loads and simply drives
    # no LEDs, which is what happens under jalv, lv2chain and any non-MOD host.
    lv2:optionalFeature hmi:WidgetControl ;

    # Load bearing. mod-host only asks a plugin for its notification interface
    # if the plugin advertises it here; without this line every addressing to a
    # hardware actuator silently does nothing.
    lv2:extensionData hmi:PluginNotification ;

    # The preset button recalls a slot by writing the engine directly, not the
    # control ports - a plugin cannot write its own ports. Without state, a
    # pedalboard saved after a recall would store the stale knob values and
    # reload the wrong sound.
    lv2:extensionData state:interface ;
    rdfs:comment \"\"\"16-channel Feedback Delay Network algorithmic reverb.

FWHT feedback matrix with coprime prime-number delay allocation, seven
algorithms (Room, Hall, Plate, Spring, Goldfoil), per-channel 10-band
Valimaki-Liski cascade GEQ absorption for frequency-dependent RT60,
ISM early reflections, ADAA saturation, ducking and a brick-wall limiter.\"\"\" ;
""" % (URI, VERSION[0], VERSION[1])]

    port_blocks = []

    for i, (sym, name, direction) in enumerate(P.AUDIO_PORTS):
        cls = "lv2:InputPort" if direction == "input" else "lv2:OutputPort"
        port_blocks.append("""    [
        a %s , lv2:AudioPort ;
        lv2:index %d ;
        lv2:symbol "%s" ;
        lv2:name "%s"
    ]""" % (cls, i, sym, name))

    for i, p in enumerate(P.CONTROL_PORTS):
        idx = P.FIRST_CONTROL_INDEX + i
        lines = ["        a lv2:InputPort , lv2:ControlPort ;",
                 "        lv2:index %d ;" % idx,
                 '        lv2:symbol "%s" ;' % p["sym"],
                 '        lv2:name "%s" ;' % p["name"]]

        props = []
        if p["kind"] in ("enum", "slot_preset"):
            props += ["lv2:integer", "lv2:enumeration"]
        elif p["kind"] == "bool":
            props += ["lv2:toggled"]
        elif p["kind"] == "trigger":
            # What mod-ui offers to a footswitch as a momentary button. The
            # host returns the port to its default after the press, so run()
            # only ever sees a rising edge. connectionOptional so a host that
            # ignores these still loads the plugin.
            #
            # NOTE the namespace: trigger lives in port-props, NOT lv2core.
            # `lv2:trigger` is an undefined term, and writing it is silently
            # half-broken rather than an error - mod-ui matches port properties
            # on their local name alone (utils_lilv.cpp: strrchr(uri, '#') + 1)
            # so it still displays as a trigger, while mod-host matches the
            # real URI (LV2_PORT_PROPS__trigger) and does not. Without
            # HINT_TRIGGER mod-host falls through to its HINT_TOGGLE branch,
            # "toggle, always min or max", and the pad LATCHES: press, press
            # again to unlatch, press a third time to fire. That is the
            # two-pushes-per-recall bug.
            props += ["lv2:toggled", "pprops:trigger", "lv2:connectionOptional"]
        elif p["skew"] < 1.0:
            # LV2's only nonlinear taper. Not identical to a JUCE skew but the
            # same intent: put the useful range under the first half of the
            # knob. predelay keeps skew 1.0 precisely because its 0.0 minimum
            # makes a logarithmic taper undefined.
            props += ["pprops:logarithmic"]

        for prop in props:
            lines.append("        lv2:portProperty %s ;" % prop)

        is_int = p["kind"] in ("enum", "bool", "slot_preset", "trigger")
        conv = int if is_int else float
        lines.append("        lv2:default %s ;" % num(conv(p["default"])))
        lines.append("        lv2:minimum %s ;" % num(conv(p["lo"])))
        lines.append("        lv2:maximum %s" % num(conv(p["hi"])))

        if p["points"]:
            lines[-1] += " ;"
            # One predicate, a comma-separated object list. Repeating
            # `lv2:scalePoint` after each comma is not Turtle.
            pts = ['[ rdfs:label "%s" ; rdf:value %d ]' % (label, v)
                   for v, label in enumerate(p["points"])]
            lines.append("        lv2:scalePoint "
                         + (" ,\n" + " " * 23).join(pts))

        if p["unit"]:
            lines[-1] += " ;"
            lines.append("        units:unit %s" % UNIT_TTL[p["unit"]])

        port_blocks.append("    [\n" + "\n".join(lines) + "\n    ]")

    for i, p in enumerate(P.OUTPUT_PORTS):
        idx = P.FIRST_OUTPUT_INDEX + i
        port_blocks.append("""    [
        a lv2:OutputPort , lv2:ControlPort ;
        lv2:index %d ;
        lv2:symbol "%s" ;
        lv2:name "%s" ;
        lv2:portProperty lv2:integer , lv2:connectionOptional ;
        lv2:default %d ;
        lv2:minimum %d ;
        lv2:maximum %d
    ]""" % (idx, p["sym"], p["name"], int(p["default"]), int(p["lo"]), int(p["hi"])))

    out.append("    lv2:port\n" + " ,\n".join(port_blocks) + " .\n")
    write(os.path.join(BUNDLE, "AmbienceReverb.ttl"), "\n".join(out))


